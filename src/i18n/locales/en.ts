/**
 * 문자열 리터럴을 string 으로 넓힌다.
 * en 을 `as const` 로 선언해도 다른 사전은 각자의 언어로 값을 담을 수 있어야 한다.
 */
type Widen<T> = T extends string ? string : { [K in keyof T]: Widen<T[K]> }

/** 다른 사전은 en 과 동일한 모양이어야 한다 — 누락·오타는 컴파일 에러가 된다 */
